"""Generates host/nis_spv.h (NVIDIA Image Scaling's NVScaler compute shader as SPIR-V) and host/nis_coef.h (its filter
coefficient tables) from NVIDIA's SDK files in third_party/nis (NIS_Main.glsl, NIS_Scaler.h, NIS_Config.h; v1.0.3, MIT),
used unmodified. Run after changing the shader defines: python tools/gen_nis.py
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NIS = os.path.join(ROOT, 'third_party', 'nis')
HOST = os.path.join(ROOT, 'host')
GLSLC = r'C:/VulkanSDK/1.4.363.0/Bin/glslc.exe'

# NVScaler, blocks of 32 x 24 pixels, 128 threads (NISOptimizer for NVIDIA), viewports (crop rectangles), clamped output
DEFINES = ['NIS_SCALER=1', 'NIS_GLSL=1', 'NIS_BLOCK_WIDTH=32', 'NIS_BLOCK_HEIGHT=24', 'NIS_THREAD_GROUP_SIZE=128',
           'NIS_VIEWPORT_SUPPORT=1', 'NIS_CLAMP_OUTPUT=1', 'NIS_HDR_MODE=0']


def write(path, text):
    tmp = path + '.new'
    with open(tmp, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    os.replace(tmp, path)


def main():
    spv = os.path.join(HOST, 'nis_main.spv.tmp')
    cmd = [GLSLC, '-fshader-stage=compute', '--target-env=vulkan1.2', '-O'] + ['-D' + d for d in DEFINES] + \
          [os.path.join(NIS, 'NIS_Main.glsl'), '-o', spv]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit('glslc failed:\n' + r.stdout + r.stderr)
    data = open(spv, 'rb').read()
    os.replace(spv, spv + '.done')   # kept beside, not deleted
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    lines = ['// Generated by tools/gen_nis.py from third_party/nis/NIS_Main.glsl (NVIDIA Image Scaling SDK v1.0.3, MIT);',
             '// defines: ' + ' '.join(DEFINES) + '. Do not edit.', '#pragma once', '#include <stdint.h>',
             'static const uint32_t nis_scaler_spv[] = {']
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    lines.append('};')
    write(os.path.join(HOST, 'nis_spv.h'), '\n'.join(lines) + '\n')

    cfg = open(os.path.join(NIS, 'NIS_Config.h'), encoding='utf-8').read()
    out = ['// Generated by tools/gen_nis.py: the filter tables of third_party/nis/NIS_Config.h (NVIDIA Image Scaling SDK',
           '// v1.0.3, MIT), 64 phases x 8 taps each. Do not edit.', '#pragma once']
    for name in ('coef_scale', 'coef_usm'):
        m = re.search(r'constexpr float ' + name + r'\[kPhaseCount\]\[kFilterSize\] = \{(.*?)\};', cfg, re.S)
        if not m:
            sys.exit('table %s not found' % name)
        body = m.group(1).strip()
        out.append('static const float nis_%s[64][8] = {' % name)
        out.append('    ' + body)
        out.append('};')
    write(os.path.join(HOST, 'nis_coef.h'), '\n'.join(out) + '\n')
    print('nis_spv.h: %d words; nis_coef.h written' % len(words))


main()
